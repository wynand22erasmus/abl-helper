/**
 * Builds syntaxes/research-injection.tmLanguage.json from research docs and keyword lists.
 * Run: node scripts/build-syntax-from-research.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");

function loadWordList(relPath) {
  const file = path.join(root, relPath);
  if (!fs.existsSync(file)) {
    return [];
  }
  return fs
    .readFileSync(file, "utf8")
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith("#"));
}

function keywordAlternation(words, abbreviate = true) {
  const parts = [];
  for (const w of words) {
    const upper = w.toUpperCase();
    if (!abbreviate || upper.length <= 4) {
      parts.push(upper.replace(/-/g, "\\-"));
      continue;
    }
    // Allow Progress-style abbreviations: ACCUMULATE -> accum(?:ulate|ulat|...) 
    const min = Math.max(3, Math.ceil(upper.length * 0.4));
    const stem = upper.slice(0, min).replace(/-/g, "\\-");
    const rest = upper.slice(min).replace(/-/g, "\\-");
    if (rest.length === 0) {
      parts.push(stem);
    } else {
      parts.push(`${stem}(?:${rest})?`);
    }
  }
  return parts.join("|");
}

function buildReservedPattern(words) {
  const alt = keywordAlternation(words, true);
  return {
    name: "keyword.control.reserved.abl",
    match: `(?i)(?<=^|[\\s(,])(?:${alt})(?![a-zA-Z0-9_\\-#$%])`,
    comment:
      "Reserved keywords (OpenEdge 12.8 Keyword Index Rsrv). Generated by scripts/build-syntax-from-research.mjs",
  };
}

function buildStatementPattern(words) {
  const alt = words
    .map((w) => w.toUpperCase().replace(/-/g, "\\-"))
    .join("|");
  return {
    name: "keyword.control.statement.abl",
    match: `(?i)(?<=^|[\\s(,])(?:${alt})(?![a-zA-Z0-9_\\-#$%])`,
    comment:
      "Statement keywords from docs/research-openedge-abl-reference-128.md. Generated script.",
  };
}

const reserved = loadWordList("resources/abl-reserved-keywords.txt");
const statements = loadWordList("resources/research-statement-keywords-128.txt");

const preprocessorBuiltins = [
  "BATCH-MODE",
  "FILE-NAME",
  "LINE-NUMBER",
  "OPSYS",
  "PROCESS-ARCHITECTURE",
  "SEQUENCE",
  "WINDOW-SYSTEM",
  "DISPLAY",
  "OUT",
  "OUT-FMT",
  "OUT-LONG",
  "WEBSTREAM",
];

const injection = {
  scopeName: "abl-helper.research.injection",
  injectionSelector: "L:source.abl -comment -string",
  patterns: [{ include: "#research-root" }],
  repository: {
    "research-root": {
      patterns: [
        { include: "#preprocessor-line-128" },
        { include: "#preprocessor-builtin-128" },
        { include: "#dotnet-inner-type-plus" },
        { include: "#reserved-keywords-128" },
        { include: "#statement-keywords-128" },
        { include: "#operators-keyword-index" },
      ],
    },
    "preprocessor-line-128": {
      patterns: [
        {
          begin: "(?i)^\\s*((&)(webstream))\\b",
          beginCaptures: {
            "2": { name: "punctuation.definition.preprocessor.abl" },
            "3": { name: "keyword.control.directive.preprocessor.abl" },
          },
          end: "$",
          name: "meta.preprocessor.line.abl",
        },
      ],
    },
    "preprocessor-builtin-128": {
      patterns: [
        {
          match: `(?i)(\\{)(&)(${preprocessorBuiltins.map((b) => b.replace(/-/g, "\\-")).join("|")})(\\s*\\})`,
          captures: {
            "1": { name: "punctuation.section.abl" },
            "2": { name: "punctuation.definition.preprocessor.abl" },
            "3": { name: "variable.preprocessor.builtin.abl" },
            "4": { name: "punctuation.section.abl" },
          },
          comment:
            "Built-in {&...} from OpenEdge 12.8 Keyword Index + SpeedScript (research doc).",
        },
      ],
    },
    "dotnet-inner-type-plus": {
      match: "(?i)(?<=[\\w#$%])(\\+)(?=[\\w#$%])",
      captures: {
        "1": { name: "punctuation.separator.type.abl" },
      },
      comment: ".NET inner type separator in type names (Type-name syntax 12.8).",
    },
    "reserved-keywords-128": buildReservedPattern(reserved),
    "statement-keywords-128": buildStatementPattern(statements),
    "operators-keyword-index": {
      patterns: [
        {
          match: "(<=|<>|>=)",
          captures: { "1": { name: "keyword.operator.abl" } },
          comment: "Operators indexed in OpenEdge 12.8 Keyword Index.",
        },
        {
          match: "(?i)(?<=\\s)(@)(?=\\s|\\()",
          captures: { "1": { name: "keyword.operator.abl" } },
        },
      ],
    },
  },
};

const outPath = path.join(root, "syntaxes", "research-injection.tmLanguage.json");
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, JSON.stringify(injection, null, 2) + "\n", "utf8");
console.log(`Wrote ${outPath} (${reserved.length} reserved, ${statements.length} statement keywords)`);
